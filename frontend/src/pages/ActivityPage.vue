  >
    <WorkspacePageHeader
      eyebrow="Workspace history"
      title="Activity"
      title-id="activity-title"
      subtitle="Timestamped API events, structured details, and saved optimizer-run reopening. Reopening a run does not approve any trade."
    >
      <template #actions>
        <q-btn
          unelevated
          no-caps
          type="button"
          class="primary-button"
          :disable="isLoading"
          @click="refresh"
        >
          {{ isLoading ? 'Loading…' : 'Refresh activity' }}
        </q-btn>
      </template>
    </WorkspacePageHeader>

    <WorkspaceCapabilityNotice label="DEMO ONLY.">
      This local activity view never connects to E*TRADE and contains no order preview or submission
      controls.
    </WorkspaceCapabilityNotice>

    <div class="error-stack column no-wrap q-gutter-y-sm">
      <ApiActionError
        :error="store.actionState.loadActivity.error"
        title="Activity could not be loaded"
      />
      <ApiActionError
        :error="store.actionState.openSavedRun.error"
        title="Saved optimizer run could not be reopened"
      />
    </div>

    <ResourceFreshnessNotice :resources="['activity']" />

    <RunSummary
      v-if="savedRunSummary || store.actionState.openSavedRun.pending"
      mode="saved"
      :summary="savedRunSummary"
      :context="savedRunSummary?.frozen_display_context ?? null"
      :pending="store.actionState.openSavedRun.pending"
    />

    <WorkspaceFilterPanel
      label="Activity filters"
      class="filter-panel row items-end q-gutter-sm q-pa-md"
      @submit="applyFilters"
    >
      <label class="column no-wrap q-gutter-y-xs">
        <span>Event type</span>
        <q-input
          outlined
          dense
          hide-bottom-space
          v-model="eventType"
          type="search"
          placeholder="Exact API event type"
        />
      </label>
      <label class="column no-wrap q-gutter-y-xs">
        <span>Status</span>
        <q-input
          outlined
          dense
          hide-bottom-space
          v-model="status"
          type="search"
          placeholder="Exact API status"
        />
      </label>
      <label class="column no-wrap q-gutter-y-xs">
        <span>Correlation ID</span>
        <q-input
          outlined
          dense
          hide-bottom-space
          v-model="correlationId"
          type="search"
          placeholder="Correlation ID"
        />
      </label>
      <label class="column no-wrap q-gutter-y-xs">
        <span>Since (UTC)</span>
        <q-input
          outlined
          dense
          hide-bottom-space
          v-model="since"
          type="datetime-local"
          step="any"
          @update:model-value="markDateTimeEdited('since')"
        />
      </label>
      <label class="column no-wrap q-gutter-y-xs">
        <span>Until (UTC)</span>
        <q-input
          outlined
          dense
          hide-bottom-space
          v-model="until"
          type="datetime-local"
          step="any"
          @update:model-value="markDateTimeEdited('until')"
        />
      </label>
      <label class="column no-wrap q-gutter-y-xs">
        <span>Rows per page</span>
        <q-select
          v-model="pageLimit"
          :options="[
            { label: '25', value: 25 },
            { label: '50', value: 50 },
            { label: '100', value: 100 },
            { label: '250', value: 250 },
          ]"
          emit-value
          map-options
          outlined
          dense
          hide-bottom-space
          aria-label="Rows per page"
        />
      </label>
      <q-btn unelevated no-caps type="submit" class="secondary-button" :disable="isLoading"
        >Apply filters</q-btn
      >
      <q-btn
        unelevated
        no-caps
        type="button"
        class="text-button"
        :disable="isLoading"
        @click="clearFilters"
      >
        Clear filters
      </q-btn>
    </WorkspaceFilterPanel>

    <p
      v-if="store.actionState.loadActivity.pending && !activity"
      class="state-message"
      role="status"
    >
      Loading activity from the local API…
    </p>
    <WorkspaceEmptyState v-else-if="!activity" title="No activity page loaded">
      Retry to request current activity. No events are generated by this page.
      <template #action>
        <q-btn
          unelevated
          no-caps
          type="button"
          class="secondary-button"
          :disable="isLoading"
          @click="refresh"
        >
          Retry loading activity
        </q-btn>
