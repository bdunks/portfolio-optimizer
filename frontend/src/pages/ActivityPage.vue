      >
        <li v-for="event in activity.items" :key="event.id" class="event-card q-pa-md">
          <header
            class="event-heading row no-wrap justify-between q-gutter-md items-center q-mb-sm"
          >
            <div>
              <h2 class="q-ma-none">{{ event.event_type }}</h2>
