            {{
              store.actionState.openSavedRun.pending
                ? 'Opening saved run…'
                : 'Reopen saved optimizer run'
            }}
          </q-btn>
        </li>
      </ol>
    </template>
    <WorkspacePagination
      v-if="activity"
      :offset="activity.offset"
      :limit="activity.limit"
      :total="activity.total"
      :pending="isLoading"
      label="Activity pages"
      @page="loadActivity"
    />
  </section>
